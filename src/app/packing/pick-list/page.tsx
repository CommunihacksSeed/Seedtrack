"use client";

import Link from "next/link";
import { ArrowLeft, Printer, Sprout } from "lucide-react";
import { useData } from "@/components/data-provider";
import { Button, EmptyState, Loading } from "@/components/ui";
import { seedLabel } from "@/lib/domain";
import { seedPickList } from "@/lib/views";

/** Printable pick list: every seed to pack across all approved orders, with per-order splits. */
export default function PickListPage() {
  const { state } = useData();
  if (!state) return <Loading />;
  const db = state.snapshot;
  const orders = db.orders.filter((o) => o.status === "Approved" || o.status === "Preparing");
  const groups = seedPickList(db, orders);
  const total = groups.reduce((a, g) => a + g.total, 0);

  return (
    <>
      <div className="no-print mb-4 flex items-center justify-between">
        <Link href="/packing" className="inline-flex items-center gap-1 text-sm text-muted hover:text-forest-700">
          <ArrowLeft size={14} /> Packing Queue
        </Link>
        <Button variant="primary" onClick={() => window.print()} disabled={!groups.length}>
          <Printer size={16} /> Print
        </Button>
      </div>
      {groups.length === 0 ? (
        <EmptyState title="Nothing to pack right now" />
      ) : (
        <article className="print-area mx-auto max-w-3xl rounded-2xl border border-sage-200 bg-white p-8 text-ink shadow-sm">
          <header className="flex items-end justify-between border-b-2 border-forest-800 pb-4">
            <div>
              <p className="flex items-center gap-1.5 text-sm font-semibold uppercase tracking-wider text-forest-700">
                <Sprout size={16} /> SeedFlow pick list
              </p>
              <h1 className="mt-1 font-display text-3xl font-semibold">Packets by seed</h1>
            </div>
            <p className="text-right text-sm">
              {new Date().toLocaleDateString()}
              <br />
              {groups.length} seeds · {total} packets · {orders.length} orders
            </p>
          </header>
          {groups.map((g) => (
            <section key={g.seed.id} className="break-inside-avoid border-b border-stone-300 py-4">
              <div className="flex items-baseline justify-between">
                <h2 className="text-lg font-semibold">
                  <span className="mr-2 inline-block h-4 w-4 rounded border-2 border-stone-500 align-middle" />
                  {seedLabel(g.seed)}
                </h2>
                <p className="text-xl font-semibold tabular-nums">
                  {g.total} <span className="text-sm font-normal text-muted">{g.seed.unit}</span>
                </p>
              </div>
              {g.seed.storage_location && <p className="ml-6 text-sm text-muted">Location: {g.seed.storage_location}</p>}
              <table className="ml-6 mt-2 w-[calc(100%-1.5rem)] text-sm">
                <tbody>
                  {g.lines.map(({ order, item }) => (
                    <tr key={item.id} className="border-t border-stone-100">
                      <td className="w-8 py-1.5">
                        <span className="inline-block h-4 w-4 rounded border border-stone-400 text-center text-[10px] leading-3">
                          {item.packed_quantity === item.approved_quantity ? "✓" : ""}
                        </span>
                      </td>
                      <td className="py-1.5">
                        #{order.order_number} · {order.organization_name}
                      </td>
                      <td className="py-1.5 text-right font-semibold tabular-nums">× {item.approved_quantity}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </section>
          ))}
          <p className="mt-6 text-center text-[10px] text-muted">Youth in Food Systems · Youth Seed Stewards — generated by SeedFlow (CommuniHacks 2026 prototype)</p>
        </article>
      )}
    </>
  );
}
