// Writes supabase/seed.sql: loads the FICTIONAL demo dataset via sf_reset_demo().
// Run: npm run db:seed-sql
import { writeFileSync } from "fs";
import { buildDemoSnapshot } from "../src/lib/demo-data";

const json = JSON.stringify(buildDemoSnapshot()).replace(/'/g, "''");
writeFileSync(
  "supabase/seed.sql",
  `-- DEMO DATA ONLY. All quantities, schools, names and addresses are fictional.\n` +
    `-- Generated by scripts/generate-seed-sql.ts. Replaces all existing SeedFlow data.\n` +
    `select sf_reset_demo('${json}'::jsonb, 'RESET');\n`,
);
console.log("Wrote supabase/seed.sql");
